const pick = (pair: [string, string] | undefined, lang: Language) =>
  !pair ? undefined : lang === 'pt' ? pair[0] : pair[1];

export const translateMuscle = (muscle: string, lang: Language) =>
  lang === 'en' ? muscle : pick(terms[muscle], lang) ?? muscle;

export const translateExerciseName = (ex: Exercise, lang: Language) => {
  if (lang === 'en') return ex.name;
  return ex.translations?.[lang]?.name ?? pick(names[ex.id], lang) ?? ex.name;
};

/** Returns the exercise with every text field resolved for the active language. */
export function localizeExercise(ex: Exercise, lang: Language): Exercise {
  if (lang === 'en') return ex;
  const tr = ex.translations?.[lang];
  return {
    ...ex,
    name: translateExerciseName(ex, lang),
    description: tr?.description ?? ex.description,
    instructions: tr?.instructions ?? ex.instructions,
    commonMistakes: tr?.commonMistakes ?? ex.commonMistakes,
    musclesWorked: tr?.musclesWorked ?? ex.musclesWorked.map(m => translateMuscle(m, lang)),
  };
}
